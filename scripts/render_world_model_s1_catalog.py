#!/usr/bin/env python3
"""Render or check the S1 question classes, full gold traces, and system prompt."""

from __future__ import annotations

import argparse
from collections import Counter, defaultdict
import importlib
import json
from pathlib import Path
import sys

REPO_ROOT = Path(__file__).resolve().parent.parent
sys.path.insert(0, str(REPO_ROOT))

from runtime.world_model.contract import _message_lines

SECTIONS = (1, 2, 3, 4, 6, 7, 8, 9)
DEFAULT_CORPUS = REPO_ROOT / "data/world_model_v4/corpora/s1_v10"
DEFAULT_DOCUMENT = REPO_ROOT / "agents/world_model_v3_curriculum/S1-question-classes.md"


def case_names(section: int) -> dict[int, str]:
    """Map each form number in one S1 section to its case name from the family builder."""
    module = importlib.import_module(f"runtime.world_model.s1_{section}_corpus")
    mapping = next(getattr(module, name) for name in
                   ("FORM_BY_BUCKET", "TRACE_BY_BUCKET", "FORM_BY_FAMILY")
                   if hasattr(module, name))
    return {number: name.replace("_", " ") for name, number in mapping.items()}


def gold_key(row: dict) -> tuple[int, str, str, str]:
    """Return a row's gold-trace key: current-turn calls, status, decision, blocked reason.

    The first published training row for each key within a question type is
    that type's gold trace. The curriculum dashboard uses the same rule.
    """
    messages = row["messages"]
    last_user = max(i for i, item in enumerate(messages) if item["role"] == "user")
    answer = messages[-1]["content"]
    return (
        sum("tool_call" in item for item in messages[last_user + 1:]),
        answer["status"], answer["continuation_decision"],
        row["metadata"].get("blocked_reason_code") or "",
    )


def render(corpus: Path) -> str:
    """Render counts and complete worked examples from the finalized training rows."""
    version = corpus.name.removeprefix("s1_")
    with (corpus / "s1_1/train.jsonl").open() as stream:
        system_prompt = json.loads(next(stream))["messages"][0]["content"]
    lines = [
        "# S1 Question Classes, Gold Traces, and System Prompt",
        "",
        "<!-- Generated by scripts/render_world_model_s1_catalog.py; do not hand-edit. -->",
        "",
        f"Inventory of the finalized {version} task content.",
        "Counts and outcome sets come from the published component rows;",
        "case names come from their builders. Each type below includes full gold",
        "traces selected from the finalized training rows, preserving the reviewed",
        "reasoning used by the selected corpus.",
        "",
        "There are 66 active S1 question types across eight families. S1.5 remains",
        "disabled on the context ontology. S1.6.7 is training-only (zero held-out rows).",
        "Totals: 55,000 S1 training rows, 276 S0 replay rows, 6,875 validation rows,",
        "and 6,875 test rows. A type's presence here does not imply a passed model gate.",
        "",
        "Current files:",
        "",
        f"- Selected corpus: `data/world_model_v4/corpora/s1_{version}/`.",
        f"- Selected panels: `data/world_model_v4/eval/s1_{version}/`.",
        "- V7 corpus/panels: the corresponding `s1_v7/` directories in the isolated",
        "  `../mentor-rl-s1-prompt-v7/` checkout; see [the experiment](S1-prompt-v7.md).",
        "- Family builders: `runtime/world_model/s1_<section>_corpus.py`.",
        f"- Selected configuration: `runtime/world_model/s1_{version}.yaml`.",
        "",
        f"## System prompt ({version})",
        "",
        "The prompt below is copied verbatim from the selected corpus's first row.",
        f"{version.upper()} retains the original system prompt in `runtime/world_model/contract.yaml`.",
        "The separate v7 prompt remains documented in [its experiment](S1-prompt-v7.md).",
        "",
        "```text",
        system_prompt.rstrip("\n"),
        "```",
        "",
        "The `calls` column counts only calls after the current user message.",
        "Multiple outcomes can reflect standalone/workflow framing or retry cases.",
        "",
        "## Reading the gold traces",
        "",
        "Each example includes all harness context, user turns, assistant reasoning,",
        "tool calls, tool results, and final answers, without shortening their content.",
        "The shared system prompt is printed once above. The non-system messages",
        f"are copied unchanged from {version}.",
        "The source row ID and file line identify every example.",
        "",
        "For each type, select the first published training row for every distinct",
        "combination of call count, final status, continuation decision, and",
        "blocked-reason code. This includes stop/continue outcomes, terminal",
        "failures, recovered retries, and exhausted retries where present.",
        "These are representative gold outputs, not every wording or input variant.",
        "Earlier turns remain visible and are marked as masked context.",
        "",
        "The older `runtime/world_model/golden_traces.jsonl` remains a shared wire",
        "fixture; it predates the v6 reasoning edits. The current worked examples",
        "below come from the corpus itself. S0 examples remain in",
        "[S0-question-classes.md](S0-question-classes.md).",
        "",
    ]
    for section in SECTIONS:
        names = case_names(section)
        root = corpus / f"s1_{section}"
        manifest = json.loads((root / "manifest.json").read_text())
        cases = defaultdict(lambda: {"calls": set(), "status": set(), "decision": set()})
        examples = defaultdict(dict)
        observed = Counter()
        with (root / "train.jsonl").open() as stream:
            for line_number, line in enumerate(stream, 1):
                row = json.loads(line)
                trace = row["metadata"]["source_trace"]
                variant = gold_key(row)
                calls, status, decision, _ = variant
                cases[trace]["calls"].add(calls)
                cases[trace]["status"].add(status)
                cases[trace]["decision"].add(decision)
                examples[trace].setdefault(variant, (line_number, row))
                observed[trace] += 1
        assert dict(observed) == manifest["form_counts"]["train"]
        lines.extend([
            f"## S1.{section}",
            "",
            f"Builder: `runtime/world_model/s1_{section}_corpus.py`; "
            f"component files: `s1_{section}/{{train,validation,test}}.jsonl` and `manifest.json`.",
            "",
            "| Type | Case | Train | Validation | Test | Calls | Status | Decision |",
            "|---|---|---:|---:|---:|---|---|---|",
        ])
        for number, name in sorted(names.items()):
            trace = f"S1.{section}.{number}"
            counts = [manifest["form_counts"][split].get(trace, 0)
                      for split in ("train", "validation", "test")]
            outcomes = [", ".join(map(str, sorted(cases[trace][key])))
                        for key in ("calls", "status", "decision")]
            lines.append("| " + " | ".join(map(str, (trace, name, *counts, *outcomes))) + " |")
        lines.append("")
        for number in sorted(names):
            trace = f"S1.{section}.{number}"
            lines.extend([f"### {trace}", ""])
            for index, (variant, (line_number, row)) in enumerate(
                sorted(examples[trace].items()), 1
            ):
                calls, status, decision, reason = variant
                outcome = f"{status} / {decision}" + (f" / {reason}" if reason else "")
                lines.extend([
                    f"#### Example {index}: current-turn calls: {calls}; {outcome}",
                    "",
                    f"Source: `s1_{section}/train.jsonl`, line {line_number}; "
                    f"row ID: `{row['row_id']}`.",
                    "",
                ])
                messages = row["messages"]
                users = [i for i, message in enumerate(messages) if message["role"] == "user"]
                for message_index, message in enumerate(messages):
                    if message["role"] == "system":
                        continue
                    if len(users) > 1 and message_index == users[0]:
                        lines.extend(["[Earlier turn: in context, masked]", ""])
                    if len(users) > 1 and message_index == users[-1]:
                        lines.extend(["[This turn: trained]", ""])
                    lines.extend(_message_lines(message))
                    lines.append("")
    lines.extend([
        "## Retry variants and result rules",
        "",
        "- S1.1.8: 200 terminal failures, 100 recoveries, 100 exhausted retries.",
        "- S1.2.11 and S1.3.10 also include explicit no-retry, recovered, and",
        "  exhausted cases. Policies: `s1_v6_lookup_retries.json`,",
        "  `s1_v6_id_lookup_retries.json`, and `s1_v6_membership_retries.json`",
        "  under `runtime/world_model/`.",
        "- S1.1.10 answers confirmed membership absence as resolved; S1.1.11",
        "  keeps unknown membership as `present:null` and defers.",
        "- S1.3.5–7 preserve both tools' fields. Exactly one surviving candidate",
        "  resolves identity; zero or multiple candidates leave that choice ambiguous.",
        "- S1.2.4 retains a resolved ID with `gene_symbol:null`. Replacing that null",
        "  marker across S0/S1 remains a separate future improvement.",
        "- S1.4 evaluates identity agreement; a confirmed mismatch can complete",
        "  the comparison. A workflow cue does not authorize the later operation.",
        "",
        "Re-render from the repository root:",
        "",
        "```bash",
        "python scripts/render_world_model_s1_catalog.py",
        "python scripts/render_world_model_s1_catalog.py --check",
        "```",
        "",
    ])
    return "\n".join(lines)


def main() -> None:
    """Write the consolidated document, or check it without changing any files."""
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("--corpus", type=Path, default=DEFAULT_CORPUS)
    parser.add_argument("--output", type=Path, default=DEFAULT_DOCUMENT)
    parser.add_argument("--check", action="store_true", help="fail if the document differs from its sources")
    args = parser.parse_args()
    rendered = render(args.corpus)
    if args.check:
        if not args.output.is_file() or args.output.read_text() != rendered:
            raise SystemExit(f"{args.output} is stale; run scripts/render_world_model_s1_catalog.py")
        print("S1 question classes, full gold traces, and system prompt are current (66 types)")
    else:
        args.output.write_text(rendered)


if __name__ == "__main__":
    main()
